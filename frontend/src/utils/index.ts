/**
 * Format number with locale-specific formatting
 */
export const formatNumber = (value: number, locale = 'ru-RU'): string => {
  return new Intl.NumberFormat(locale).format(value);
};

/**
 * Format date to localized string
 */
export const formatDate = (
  date: string | Date,
  options: Intl.DateTimeFormatOptions = {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  },
  locale = 'ru-RU'
): string => {
  const dateObj = typeof date === 'string' ? new Date(date) : date;
  return dateObj.toLocaleString(locale, options);
};

/**
 * Calculate percentage with optional decimal places
 */
export const calculatePercentage = (value: number, total: number, decimals = 1): number => {
  if (total === 0) return 0;
  return Math.round((value / total) * 100 * Math.pow(10, decimals)) / Math.pow(10, decimals);
};

/**
 * Get color class based on score value
 */
export const getScoreColor = (score: number): string => {
  if (score >= 90) return 'text-green-600 bg-green-50';
  if (score >= 80) return 'text-blue-600 bg-blue-50';
  if (score >= 70) return 'text-yellow-600 bg-yellow-50';
  return 'text-red-600 bg-red-50';
};

